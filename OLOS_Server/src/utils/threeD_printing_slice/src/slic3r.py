import os
import subprocess
import xml.etree.ElementTree as ET
import subprocess
import cairosvg
from utils.threeD_printing_slice.src.slicers_shared_methods import (
    generate_gcode_for_layer, prepare_contour_settings, prepare_infill_settings,
    send_slicing_progress_to_interface, generate_init_block
)
from utils.tmp_files_manager import TempFilesManager
from utils.image_to_gcode_helper import ImageToGcodeHelper
from core.constants import CoreConstants as constants


class Slic3r:
    """
    Handles slicing of 3D models using the Slic3r engine and generates G-code layer by layer.

    This class converts SVG slices generated by Slic3r into raster images and SVG contours,
    then processes them to produce printable G-code with infill and contour information.

      Attributes:
        image_to_gcode_helper (ImageToGcodeHelper): Helper for converting raster image and SVG file contents into G-code.
        _svg_tmp_file_path (str): Temporary svg file path for storing the svg output of the sliced 3D model.
    """

    def __init__(self):
        self.image_to_gcode_helper = ImageToGcodeHelper()
        # create svg tmp file
        tmp_files_manager = TempFilesManager()
        self._svg_tmp_file_path = tmp_files_manager.create_temp_file('.svg')

    @classmethod
    def slice_model(cls, slicing_data, websocket_write_queue):
        """
        Slices a 3D model using Slic3r and generates G-code for each layer.

        Args:
            slicing_data (dict): Configuration settings for slicing, including model path,
                                layer height, resolution, image size, and more.
            websocket_write_queue (asyncio.Queue): Queue used to send progress updates via WebSocket.

        Raises:
            subprocess.CalledProcessError: If the Slic3r CLI fails to execute.
        """

        slicer = cls()

        # generate svg file
        slic3r_path = os.path.abspath(
            os.path.join(__file__, "../../slicers/Slic3r/Slic3r-console.exe"))

        subprocess.run([
            slic3r_path,
            "--export-svg", slicing_data["model_file_path"],
            "--layer-height",  str(
                slicing_data["layer_height"]),
            "--output", slicer._svg_tmp_file_path
        ],
            check=True, stdout=subprocess.DEVNULL, stderr=subprocess.DEVNULL)

        tree = ET.parse(slicer._svg_tmp_file_path)
        root = tree.getroot()

        image_size = (float(root.get(
            'width')), float(root.get('height')))
        user_image_size = slicing_data["infill_image_size"] if slicing_data["use_image_size"] else image_size

        images_data = slicer._convert_slic3r_svg_to_images_data(
            root, user_image_size)

        # generate gcode from images
        if images_data:
            with open(slicing_data["gcode_file_path"], "w") as gcode_file:
                user_layer_height = slicing_data["layer_height"]
                z = 0

                # Write OLSK machine init block with bed offset
                gcode_file.write(generate_init_block(slicing_data))

                total_slic3r_layers_num = len(images_data)

                # Calculate actual number of output layers and loop step for zone exposure
                if user_layer_height > 0.5:
                    model_height = total_slic3r_layers_num / 2
                    num_layers = max(1, int(model_height / user_layer_height))
                    step = max(1, int(total_slic3r_layers_num / num_layers))
                else:
                    num_layers = total_slic3r_layers_num
                    step = 1

                layer_index = 0
                i = 0
                while i < total_slic3r_layers_num:
                    image = images_data[i]
                    if image:
                        img_infill = image.get("raster")
                        svg_contour = image.get("svg")

                        # Per-layer zone exposure settings (first / bulk / final)
                        contour_settings = prepare_contour_settings(
                            slicing_data=slicing_data,
                            layer_index=layer_index,
                            total_layers=num_layers)
                        infill_settings = prepare_infill_settings(
                            slicing_data=slicing_data,
                            image_size=image_size,
                            user_image_size=user_image_size,
                            layer_index=layer_index,
                            total_layers=num_layers)

                        gcode_content = generate_gcode_for_layer(
                            image_to_gcode_helper=slicer.image_to_gcode_helper,
                            img_infill=img_infill,
                            svg_contour=svg_contour,
                            contour_settings=contour_settings,
                            infill_settings=infill_settings,
                            z=z,
                            layer_speed=slicing_data["layer_speed"],
                            slicing_data=slicing_data,
                            layer_index=layer_index)

                        gcode_file.write(gcode_content)
                        layer_index += 1

                    z += user_layer_height
                    i += step

                    send_slicing_progress_to_interface(
                        websocket_write_queue=websocket_write_queue,
                        layer_index=layer_index,
                        total_layers=num_layers)

                gcode_file.write(
                    slicer.image_to_gcode_helper.add_end_of_job_commands())

    def _convert_slic3r_svg_to_images_data(self, root, image_size=None):
        """
        Parses the SVG file generated by Slic3r and converts each layer into a raster image and SVG path.

        Args:
            root (xml.etree.ElementTree.Element): Root element of the parsed SVG tree.
            image_size (tuple, optional): Desired dimensions of the output images (width, height).

        Returns:
            list: A list of dictionaries, each containing the raster image and SVG content for one layer.
        """

        # Namespace
        ns = {
            'svg': 'http://www.w3.org/2000/svg',
            'slic3r': 'http://slic3r.org/namespaces/slic3r'
        }

        all_group_elements = root.findall("svg:g", ns)

        images_data = []

        # Loop through groups and polygons
        for group_elem in all_group_elements:
            svg_content = self._generate_svg_element(
                group_elem, ns, root.get('width'), root.get('height'))

            if svg_content:
                # convert svg to image
                raster_image_content = cairosvg.svg2png(
                    bytestring=svg_content,
                    output_width=image_size[0],
                    output_height=image_size[1])

                # each layer converted to svg element and raster image
                images_data.append({
                    "svg": svg_content,
                    "raster": raster_image_content
                })
            else:
                images_data.append(None)

        return images_data

    def _generate_svg_element(self, group_elem, ns, width, height):
        """
        Generates a minimal SVG string from a <g> element containing polygon data.

        Args:
            group_elem (Element): The <g> XML element containing polygon children.
            ns (dict): XML namespace dictionary for Slic3r and SVG.
            width (str): Width of the SVG canvas.
            height (str): Height of the SVG canvas.

        Returns:
            bytes or None: UTF-8 encoded SVG string if polygons exist, otherwise None.
        """

        polygon_elem_list = group_elem.findall("svg:polygon", ns)
        if len(polygon_elem_list):
            # Minimal SVG with path
            svg_content = f'<svg xmlns="http://www.w3.org/2000/svg" width="{width}" height="{height}">'
            for polygon_elem in polygon_elem_list:
                path_elem = self._polygon_to_path(polygon_elem)
                if path_elem is not None:
                    svg_content += ET.tostring(path_elem, encoding='unicode')
            svg_content += "</svg>"
            return svg_content.encode('utf-8')
        return None

    def _polygon_to_path(self, polygon_elem):
        """
        Converts a <polygon> SVG element into an equivalent <path> SVG element.

        Args:
            polygon_elem (Element): The polygon XML element to convert.

        Returns:
            Element or None: A new SVG path element or None if points attribute is missing.
        """

        # Get the points attribute from the polygon
        points = polygon_elem.attrib.get("points", "").strip()
        if not points:
            return None  # or raise an error

        # Parse the points into a list of (x, y) tuples
        coords = [tuple(map(float, point.split(',')))
                  for point in points.split()]

        # Construct the path data string
        path_data = f"M {coords[0][0]},{coords[0][1]}"
        for x, y in coords[1:]:
            path_data += f" L {x},{y}"
        path_data += " Z"  # Close the path

        # Create the new path element and copy attributes
        path_elem = ET.Element("path")
        path_elem.set("d", path_data)

        # Copy other attributes (like fill, stroke, etc.)
        for attrib in polygon_elem.attrib:
            if attrib != "points":
                path_elem.set(attrib, polygon_elem.attrib[attrib])

        path_elem.set("stroke", "black")

        return path_elem
